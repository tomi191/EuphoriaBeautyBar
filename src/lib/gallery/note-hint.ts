/**
 * Подсказката под полето «Какво се вижда?» в листа «Снимка от работата» (№8 В2).
 * Примерът е според услугата; текстовете са на Саиф (доклад 2026-11-22-content-снимки-от-приложението, 1.1).
 */
export function noteHintForService(serviceName: string | null | undefined): string {
  const s = (serviceName ?? "").toLowerCase();
  if (/педикюр/.test(s)) return "Напр. „червен лак, чисти кантове“";
  if (/маникюр|нокт|гел лак/.test(s)) return "Напр. „бледорозов, бадемова форма“";
  if (/балая|балеаж/.test(s)) return "Напр. „медено русо, меки вълни“";
  if (/боядис/.test(s)) return "Напр. „кестеняво, гладка коса“";
  if (/грим/.test(s)) return "Напр. „опушено око, топли тонове“";
  if (/приче|кок|плитк/.test(s)) return "Напр. „нисък кок, оплетена кичурка“";
  return "Напр. „цвят, форма, дължина“";
}
