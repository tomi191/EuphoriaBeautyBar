async function main() {
  const apply = process.argv.includes("--apply");
  const { db, schema } = await import("../src/lib/db");
  const { markdownToBlocks } = await import("../src/lib/blog-writer/markdown-to-blocks");
  const { calculateReadingTime } = await import("../src/lib/blog-writer/slug");

  const blocks = markdownToBlocks(MARKDOWN);
  const readingMinutes = calculateReadingTime(MARKDOWN);
  console.log(apply ? "=== APPLY ===" : "=== DRY-RUN (без запис; --apply за запис) ===");
  console.log("slug:", SLUG, "| blocks:", blocks.length, "| reading:", readingMinutes, "мин | words:", MARKDOWN.split(/\s+/).length);

  const existing = await db.query.blogPosts.findFirst({
    where: (p) => eq(p.slug, SLUG),
    columns: { id: true },
  });
  if (existing) {
    console.log("Постът вече съществува:", SLUG, existing.id);
    process.exit(0);
  }
  if (!apply) process.exit(0);

  const id = nanoid();
  const now = new Date();
  await db.insert(schema.blogPosts).values({
    id,
    slug: SLUG,
    title: TITLE,
    excerpt: EXCERPT,
    category: CATEGORY,
    cover: COVER,
    audioUrl: null,
    contentJson: blocks,
    publishedAt: now,
    readingMinutes,
    status: "draft",
    createdAt: now,
    updatedAt: now,
  });
  console.log("=== DRAFT CREATED ===", id);
  process.exit(0);
}

main().catch((e) => {
  console.error("✗", e instanceof Error ? e.message : e);
  process.exit(1);
});
